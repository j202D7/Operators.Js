// Arithmetic Operations

// 1. Addition
let num1 = 10;
let num2 = 5;
let sum = num1 + num2;
console.log(sum);

// 2. Subtraction
let difference = num1 - num2;
console.log(difference);

// 3. Multiplication
let product = num1 * num2;
console.log(product);


// String Operations

// 4. Concatenation with +
let str1 = "Hello";
let str2 = "World";
let combinedString = str1 + " " + str2;
console.log(combinedString);
